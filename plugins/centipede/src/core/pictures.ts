// Story cp1-3 (GREEN, Julia) — picture-ROM transcription. The two rev-2 picture
// chips (136001.201/202, byte-identical to the rev-4 shipped chips 136001-211/212
// — see docs/rom-study/pictures.md) decoded into a pure data module: two 2KB
// bitplanes plus a naming table of stamp offsets. NO hand-authored pixels: every
// byte in PLANE_LOWER/PLANE_UPPER is a verbatim transcription of the ROM chip
// (generated programmatically from the vendored binary, never hand-typed), gated
// byte-for-byte and by SHA-256 in tests/pictures.test.ts (AC-1/AC-4); STAMPS
// carries offsets only, never pixel literals (AC-4).
//
// CORE MODULE — tests/purity.test.ts sweeps this file: no browser globals, no
// wall clock, no ambient entropy, no file I/O (the plane bytes below are inline
// literals; only the test and the bake tool read the ROM binaries from disk).
//
// ─── DECODE-LAYOUT GROUND TRUTH (radix-cited; docs/rom-study/claims/05-pictures.json) ──
// CENPIC.MAC (revision.v2/CENPIC.MAC) is `.RADIX 16` (:8), `.ASECT`. The assembled
// image is 0x1000 bytes: `.=0` "LOWER BIT FOR 8X16 MOTION OBJECTS" (:12) is the
// LOWER bitplane, region 0x000-0x7FF — chip 136001.201. `.=800` "UPPER BIT OF 8 X
// 16 MOTION OBJECT STAMPS" (:156) is the UPPER bitplane, region 0x800-0xFFF — chip
// 136001.202 — the SAME stamp layout mirrored: the upper-plane byte for a stamp at
// region offset X (X<0x800) is region[X+0x800], i.e. PLANE_UPPER[X] (PLANE_UPPER
// holds only the chip's own 0x800 bytes, so no +PLANE_SIZE re-offset is needed once
// indexed into the chip's own array). `.=200` "8X8 PLAYFIELD STAMPS" (:53) is the
// tile block (unlabelled, `.BYTE`+`;comment` only). MAME corroborates: gfx1 region
// 0x1000 with 136001-211.f7@0x0000 + 136001-212.hj7@0x0800 (centiped.cpp:2033-2035);
// planar 2bpp layout `spritelayout {8,16, RGN_FRAC(1,2), 2 planes, planeoffset
// {RGN_FRAC(1,2),0}, xoffset {0..7}}` (centiped.cpp:1722-1732) — pixel x=0 is the
// MSB (0x80), colour = (upperBit<<1) | lowerBit. Motion objects are 8x16 (16
// bytes/plane); playfield stamps are 8x8 (8 bytes/plane). Head/body share ONE
// sprite pool (CENDEF.MAC:129-137, CENTI4.MAC:478/500) — HEAD0..HEADF, no separate
// BODY set.

/** Total assembled picture image, both planes (bytes). CENPIC.MAC:8 (.RADIX 16), :12/:156. */
export const REGION_SIZE = 0x1000

/** One bitplane / one ROM chip (bytes). REGION_SIZE / 2 — CENPIC.MAC :12 (.=0) vs :156 (.=800). */
export const PLANE_SIZE = 0x800

/** Motion-object stamp geometry (8 wide x 16 tall) — CENPIC.MAC:12, 16-byte .BYTE rows. */
export const SPRITE_W = 8
export const SPRITE_H = 16

/** Playfield stamp geometry (8 wide x 8 tall) — CENPIC.MAC:53 (.=200), 8-byte .BYTE rows. */
export const TILE_W = 8
export const TILE_H = 8

export type StampKind = 'sprite' | 'tile'

export interface Stamp {
  /** CENPIC.MAC label (motion objects) or the convention name for a commented tile. */
  readonly name: string
  readonly kind: StampKind
  /** Lower-plane region offset (0..0x7FF); the matching upper plane is PLANE_UPPER at the same index. */
  readonly offset: number
}

