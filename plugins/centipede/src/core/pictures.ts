/**
 * Decode one stamp's two planes into a rows x 8 grid of 2-bit colour indices
 * (0-3): colour = (upperBit << 1) | lowerBit, pixel x=0 is the MSB (0x80), and
 * row r is PLANE_LOWER[stamp.offset + r] / PLANE_UPPER[stamp.offset + r]. Pure —
 * reads only the module-level plane arrays, no I/O.
 */
export function decodeStamp(stamp: Stamp): number[][] {
  const rows = stamp.kind === 'sprite' ? SPRITE_H : TILE_H
  const grid: number[][] = []
  for (let r = 0; r < rows; r++) {
    const lower = PLANE_LOWER[stamp.offset + r]
    const upper = PLANE_UPPER[stamp.offset + r]
    const row: number[] = []
    for (let x = 0; x < 8; x++) {
      const mask = 0x80 >> x // x=0 is the MSB
      const lowerBit = lower & mask ? 1 : 0
      const upperBit = upper & mask ? 1 : 0
      row.push((upperBit << 1) | lowerBit)
    }
    grid.push(row)
  }
  return grid
}
