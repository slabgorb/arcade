#!/usr/bin/env node
// tools/bake-graphics.mjs — regenerate the committed src/shell/stamp-data.ts
// module from the licence-walled picture EPROMs (ml2-4, the pac-man model:
// plugins/pac-man/tools/bake-graphics.mjs). "Bake, don't fetch": the running
// game imports decoded data and never loads a .rom at runtime, so the
// reference bytes stay gitignored while the decoded output is in-tree and
// diffable.
//
// THE REGION LAW (prose citation, never copied — GPL): MAME's gfx1 region
// loads 136013-107.r5 FIRST (0x0000) and 136013-106.p5 SECOND (0x0800)
// (centiped.cpp:2226-2227, pinned by the ml2-1 byte claims in
// docs/rom-study/claims/06-graphics.json). ml2-2's decodeStamp treats the
// first half of the region as the LOW bitplane and the second as the HIGH, so
// the bake concatenates 107.r5 then 106.p5. The visual playtest at
// /millipede/ is the final arbiter of that ordering (playbook §4).
//
// This tool is a THIN driver — read bytes, call the ml2-2 seam, write the
// module. Decode logic lives ONLY in src/shell/gfx-rom.ts (pure, imported
// here as .ts under Node's type stripping, the ml2-2 AC-4 probe's leg).
// Later graphics shapes EXTEND this file with their own read → decode → emit
// block; they don't restructure it.
//
// Usage:
//   node plugins/millipede/tools/bake-graphics.mjs
//   (or, from the plugin directory)  node tools/bake-graphics.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { decodeStamp } from '../src/shell/gfx-rom.ts'

const pluginRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
// The vendored tree sits at the MONOREPO root — two levels above the plugin.
const vendoredRoot = join(pluginRoot, '..', '..', 'reference', 'original-source', 'millipede')
const outPath = join(pluginRoot, 'src', 'shell', 'stamp-data.ts')

const LOW_PLANE_FILE = '136013-107.r5' // gfx1 @0x0000 → first half → low plane
const HIGH_PLANE_FILE = '136013-106.p5' // gfx1 @0x0800 → second half → high plane
const PLANE_SIZE = 2048

function readEprom(file) {
  const bytes = new Uint8Array(readFileSync(join(vendoredRoot, file)))
  if (bytes.length !== PLANE_SIZE) {
    throw new Error(`${file}: expected ${PLANE_SIZE} bytes, got ${bytes.length} — wrong or truncated EPROM image`)
  }
  return bytes
}

function bakeStamps() {
  const low = readEprom(LOW_PLANE_FILE)
  const high = readEprom(HIGH_PLANE_FILE)
  const region = new Uint8Array(PLANE_SIZE * 2)
  region.set(low, 0)
  region.set(high, PLANE_SIZE)

  const stamps = Array.from({ length: 256 }, (_, i) => decodeStamp(region, i * 8))

  const body =
    '// GENERATED by tools/bake-graphics.mjs from the licence-walled picture EPROMs\n' +
    '// under reference/original-source/millipede/; do not hand-edit. The\n' +
    '// byte-equality tests in tests/stamp-data.test.ts assert equality against a\n' +
    '// fresh re-decode of the vendored EPROMs (and, ROM-less, against the ml2-1\n' +
    '// byte claims).\n' +
    '//\n' +
    `// Region order (MAME gfx1, centiped.cpp:2226-2227, cited in prose): ${LOW_PLANE_FILE}\n` +
    `// first (low bitplane), ${HIGH_PLANE_FILE} second (high bitplane); decode:\n` +
    '// src/shell/gfx-rom.ts (decodeStamp, ml2-2).\n\n' +
    `/** The EPROM occupying the region's FIRST half — the LOW bitplane. */\n` +
    `export const LOW_PLANE_FILE = '${LOW_PLANE_FILE}'\n\n` +
    `/** The EPROM occupying the region's SECOND half — the HIGH bitplane. */\n` +
    `export const HIGH_PLANE_FILE = '${HIGH_PLANE_FILE}'\n\n` +
    '/** All 256 8x8 stamps: 8 rows of 8 pixels, each a 2-bit colour index 0..3. */\n' +
    'export const STAMPS: readonly (readonly (readonly number[])[])[] = [\n' +
    stamps.map((s) => `  [${s.map((row) => `[${row.join(',')}]`).join(',')}],`).join('\n') +
    '\n]\n'

  writeFileSync(outPath, body)
  console.log(`wrote ${outPath} (${stamps.length} stamps)`)
}

bakeStamps()
