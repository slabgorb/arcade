// src/shell/glyphs.ts
//
// Story mc9-4 (GREEN, Loki) — the cabinet's ALPHANUMERIC STAMP FONT as pure shell
// render data. mc3-5 drew the HUD with a `${hud}px monospace` browser font + fillText
// and deferred the authentic glyphs to mc9; this module ports them straight from the
// W3DSUP stamp font, the same 8x8 raster stamp layer mc9-1 used for cities and bases
// (src/shell/stamps.ts).
//
// PURE SHELL DATA: plain constants + a lookup, no canvas, no clock, no core import.
// render.ts (the shell) decodes each glyph with stampPixels() and paints it; nothing
// here draws.
//
// ─── SOURCE OF TRUTH: W3DSUP.MAC (the framebuffer stamp font) ─────────────────
// Missile Command is a RASTER machine. Text is drawn one 8-row bitmap "stamp" per
// character, exactly like a city quadrant: CONVERT AN ASCII VALUE TO ITS STAMP ADDRESS
// (W3DSUP.MAC:1754) maps an ASCII byte to a glyph in one of two 8-byte-per-entry tables
// — NUMBER (digits 0-9, W3DSUP.MAC:3552) and LETTER (A-Z, W3DSUP.MAC:3574) — and
// WRITE A STAMP (W3DSUP.MAC:587) blits the 8 rows. The score readout is DISPLAY 6
// DIGITS / DSPNUM (W3DSUP.MAC:2202), leading zeros suppressed.
//
// ─── ROW ORDER (measured, not assumed) ───────────────────────────────────────
// The glyph bitmaps are emitted by the BUMP macro (W3DSUP.MAC:3544):
//     .MACRO BUMP A,B,C,D,E,F,G,H
//     .BYTE   H,G,F,E,D,C,B,A          ; reverses its args into memory
//     .ENDM
// The BUMP ARGUMENTS are written top row first (arg A = top, arg H = bottom) — read
// `BUMP 000,038,06C,0C6,0C6,0FE,0C6,0C6 ; "A"` top-to-bottom and the apex/cross-bar/legs
// of an "A" are plain. render.ts paints rows[0] at the TOP of the glyph (v = pos.v +
// (STAMP_H-1-row)), so each table below is the BUMP ARGS IN WRITTEN ORDER (top→bottom) —
// NOT the reversed bytes the assembler stores — giving an upright glyph through the
// existing stamp pipeline. Verbatim ROM values; only the (documented) row order is
// re-seated to render.ts's top-first convention.

// A glyph is the cabinet's 8-wide × 8-row stamp — the same cell as every other stamp
// (STAMP_W/STAMP_H in stamps.ts); stampPixels() decodes these rows and render.ts paints
// them at the HUD scale.

