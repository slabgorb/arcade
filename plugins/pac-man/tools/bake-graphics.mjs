#!/usr/bin/env node
// tools/bake-graphics.mjs — regenerate the committed src/shell/*-data.ts
// modules from the citation-gated ROMs under reference/graphics/ (pm3-1).
//
// Story pm3-3 bakes the colour palette. This tool is EXTENDED, not rewritten,
// by pm3-4 (tile data from pacman.5e/5f) and pm3-5/6 (sprite + glyph data):
// each later task adds its own read-ROM -> decode -> emit-module block below,
// alongside PALETTE, rather than restructuring this file.
//
// Usage:
//   node plugins/pac-man/tools/bake-graphics.mjs
//   (or, run from the plugin directory)  node tools/bake-graphics.mjs
//
// Every emitted module is generated data ONLY — decode logic lives in
// src/shell/gfx-rom.ts (pure, tested independently in tests/shell/palette.test.ts)
// so this tool stays a thin "read bytes, call the decoder, write the module"
// driver per ROM.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  decodePaletteFromProm,
  decodeColourLookupFromProm,
  decodeTilePixel,
  decodeSpritePixel,
} from '../src/shell/gfx-rom.ts'

const pluginRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const graphicsDir = join(pluginRoot, 'reference', 'graphics')
const outDir = join(pluginRoot, 'src', 'shell')

const HEADER =
  '// GENERATED by tools/bake-graphics.mjs from the citation-gated reference/graphics/*;\n' +
  '// do not hand-edit; that module\'s byte-equality test asserts equality against\n' +
  '// a fresh re-decode of the vendored ROM.\n'

function formatTriples(triples) {
  return triples.map(([r, g, b]) => `  [${r}, ${g}, ${b}],`).join('\n')
}

function bakePalette() {
  const paletteProm = readFileSync(join(graphicsDir, '82s123.7f'))
  const lookupProm = readFileSync(join(graphicsDir, '82s126.4a'))

  const palette = decodePaletteFromProm(paletteProm).slice(0, 16)
  const lookup = decodeColourLookupFromProm(lookupProm)

  const body =
    HEADER +
    '//\n' +
    '// Source PROMs: reference/graphics/82s123.7f (16 colours, resistor-DAC RGB)\n' +
    '// and reference/graphics/82s126.4a (256-entry colour-lookup, low nibble).\n' +
    '// Decode: src/shell/gfx-rom.ts (decodePaletteFromProm / decodeColourLookupFromProm).\n\n' +
    '/** The 16 hardware colours, decoded from 82s123.7f (MAME pacman_palette). */\n' +
    'export const HARDWARE_PALETTE: readonly (readonly [number, number, number])[] = [\n' +
    formatTriples(palette) +
    '\n]\n\n' +
    '/** 256-entry colour-lookup table from 82s126.4a: index by colorCode * 4 +\n' +
    ' * pixelValue, value is a palette index into HARDWARE_PALETTE. */\n' +
    'const COLOUR_LOOKUP: readonly number[] = [\n  ' +
    lookup.join(', ') +
    '\n]\n\n' +
    '/** Palette index for a given colour code (0..63) and pixel value (0..3),\n' +
    ' * decoded from the 82s126.4a low nibble (MAME pacman colortable decode). */\n' +
    'export function colourLookup(colorCode: number, pixelValue: number): number {\n' +
    '  return COLOUR_LOOKUP[colorCode * 4 + pixelValue]\n' +
    '}\n'

  writeFileSync(join(outDir, 'palette-data.ts'), body)
  console.log(`wrote ${join(outDir, 'palette-data.ts')} (${palette.length} colours, ${lookup.length} lookup entries)`)
}

function bakeTiles() {
  const rom = readFileSync(join(graphicsDir, 'pacman.5e'))

  const tiles = Array.from({ length: 256 }, (_, i) =>
    Uint8Array.from({ length: 64 }, (_, k) => decodeTilePixel(rom, i, k % 8, (k / 8) | 0)),
  )

  const body =
    HEADER +
    '//\n' +
    '// Source ROM: reference/graphics/pacman.5e (256 tiles x 16 bytes, 2bpp planar).\n' +
    '// Decode: src/shell/gfx-rom.ts (decodeTilePixel, MAME charlayout).\n\n' +
    '/** 256 tiles, each 64 palette-group indices (0..3) in row-major 8x8 order.\n' +
    ' * Decoded from pacman.5e; the tile test re-derives this and asserts\n' +
    ' * byte-equality. */\n' +
    'export const TILES: readonly Uint8Array[] = [\n' +
    tiles.map((t) => `  Uint8Array.of(${t.join(', ')}),`).join('\n') +
    '\n]\n'

  writeFileSync(join(outDir, 'tile-data.ts'), body)
  console.log(`wrote ${join(outDir, 'tile-data.ts')} (${tiles.length} tiles)`)
}

// pm3-5: the sprite ROM (pacman.5f), decoded by decodeSpritePixel (MAME
// spritelayout, gfx-rom.ts). decodeSpritePixel's own (x,y) contract is
// MAME's spritelayout coordinate verbatim (see that function's header) — but
// assembling those into a 16x16 image the naive way (x=column, y=row,
// direct) comes out visibly rotated 90° from screen-upright: a ghost-body
// sprite decoded that way shows its dome on the LEFT edge and its wavy
// skirt on the RIGHT, with its two eyes stacked VERTICALLY — a real Pac-Man
// ghost never draws that way, its eyes are always side-by-side. Rendered as
// a PNG and inspected (both the raw and the rotated candidate), the
// x' = y, y' = 15-x correction (a 90° clockwise turn) is what puts the dome
// on top, the skirt on the bottom, and the two eyes side-by-side — confirmed
// numerically too, not just by eye: computing each ghost-body sprite's
// pupil-pixel (value 1) centroid AFTER this correction gives a clean,
// unambiguous per-direction grouping (sprites 32/33 centre right, 34/35
// centre down, 36/37 centre left, 38/39 centre up) that does not appear
// before it. This is consistent with Pac-Man's real cabinet — a portrait
// monitor driven by video hardware MAME's own driver rotates for display —
// but that rotation is not itself something pm3-1 vendored or cited, so it
// is recorded here as an AUTHORED, empirically-verified assembly choice, not
// a MAME-sourced fact. tests/shell/sprites.test.ts's "fresh decode" applies
// the identical x'=y,y'=15-x transform, so the byte-equality check still
// pins this choice against a regression, same as every other baked module.
function bakeSprites() {
  const rom = readFileSync(join(graphicsDir, 'pacman.5f'))

  const sprites = Array.from({ length: 64 }, (_, i) =>
    Uint8Array.from({ length: 256 }, (_, k) => {
      const x = k % 16
      const y = (k / 16) | 0
      return decodeSpritePixel(rom, i, y, 15 - x)
    }),
  )

  const body =
    HEADER +
    '//\n' +
    '// Source ROM: reference/graphics/pacman.5f (64 sprites x 64 bytes, 2bpp planar).\n' +
    '// Decode: src/shell/gfx-rom.ts (decodeSpritePixel, MAME spritelayout), assembled\n' +
    '// with the 90-degree rotation correction this function documents above.\n\n' +
    '/** 64 sprites, each 256 palette-group indices (0..3) in row-major 16x16\n' +
    ' * screen-upright order (see the rotation-correction comment above).\n' +
    ' * Decoded from pacman.5f; the sprite test re-derives this and asserts\n' +
    ' * byte-equality. */\n' +
    'export const SPRITES: readonly Uint8Array[] = [\n' +
    sprites.map((s) => `  Uint8Array.of(${s.join(', ')}),`).join('\n') +
    '\n]\n'

  writeFileSync(join(outDir, 'sprite-data.ts'), body)
  console.log(`wrote ${join(outDir, 'sprite-data.ts')} (${sprites.length} sprites)`)
}

// pm3-6 note: glyph-data.ts (FRUIT_SPRITE/SCORE_SPRITE) is deliberately NOT
// baked by this tool and has no bake*() function here. Every other module
// this file writes is re-derivable ROM pixel data (a decode function applied
// to vendored bytes, re-checked byte-for-byte by that module's test) —
// glyph-data.ts holds no pixel data at all, just two small hand-authored
// records mapping an already-decoded SPRITES index to a fruit kind or a
// score value (picked by rendering candidate sprites and inspecting shape,
// see that file's header). Generating it from this driver would misstate it
// as ROM data re-derivable from bytes, which it is not.
bakePalette()
bakeTiles()
bakeSprites()
